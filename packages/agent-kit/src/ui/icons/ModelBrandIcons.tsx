"use client";

/**
 * 知名模型的品牌字形。
 *
 * 绝大多数是自绘的「意象剪影」（不是官方 logo 的复刻）；唯 deepseek 用的是官方鲸鱼 mark
 * 的路径（取自 Simple Icons，CC0-1.0）—— 见下方 case 里的说明。
 *
 * 背景：CodeBuddy 下发的 `meta.iconUrl` 覆盖率并不满（实测同一账号 19 个模型里只有 2 个带图），
 * 而模型下拉里绝大多数行都是一线厂商的主力模型 —— 全部退化成同一个占位方块会让列表失去辨识度。
 * 所以这里按「模型 id / 名称」匹配到品牌，用一套自绘的单色字形顶上；匹配不到才用通用兜底立方体。
 *
 * 设计约束（决定了每个图形的画法）：
 * - **必须在 16px（实际绘制约 13px）可辨**：所以只用「一整块实心剪影」或「单个字母」，
 *   不用细线稿 —— 线稿在这个尺寸会糊成一团灰。这也是它们与兜底字形（描边立方体）的视觉区分：
 *   实心 = 认识的品牌，描边 = 通用占位。
 * - **单色**：`fill="currentColor"`，跟随主题 ink 色，和 kit 的黑白灰基座一致；不猜品牌主色，
 *   避免出现「颜色不对但形状对」的四不像。
 * - **几何居中**：全部图形在 24×24 视框内上下左右居中（竖向重心 ≈ 12），混排时不会一高一低。
 *
 * 每个字形的取意：
 *   deepseek → 鲸（官方 mark：圆身 + 右尾鳍 + 眼睛/胸鳍镂空）
 *   glm      → 字母 Z（智谱 / Z.ai）             kimi    → 月牙（月之暗面）
 *   minimax  → 双峰 M                            step    → 四角星（阶跃星辰）
 *   mimo     → 圆角方框 + M（小米 Mi 的方框语言） bunny   → 兔耳圆脸（space-bunny）
 */
import type { SVGProps } from "react";

export type ModelBrand = "deepseek" | "glm" | "kimi" | "minimax" | "step" | "mimo" | "bunny";

type IconProps = SVGProps<SVGSVGElement>;

/**
 * 品牌匹配表：**顺序有意义**（先匹配到的胜出）。
 * 只认模型 id / 展示名，不认 `meta.vendor` —— CodeBuddy 下发的 vendor 是加密过的单字母（"e"/"f"/"j"），
 * 拿它做判断会把 deepseek 和 kimi 归成同一家。
 */
const BRAND_PATTERNS: ReadonlyArray<readonly [ModelBrand, RegExp]> = [
  ["deepseek", /deepseek/i],
  ["glm", /glm|chatglm|zhipu|智谱/i],
  ["kimi", /kimi|moonshot|月之暗面/i],
  ["minimax", /minimax|mini-max/i],
  ["mimo", /mimo/i],
  ["step", /^step|stepfun|阶跃/i],
  ["bunny", /bunny|兔/i],
];

/** 按模型 id / 展示名匹配品牌；都不命中返回 null（调用方随即走兜底字形）。 */
export function modelBrandOf(id?: string, name?: string): ModelBrand | null {
  for (const source of [id, name]) {
    const text = (source || "").trim();
    if (!text) continue;
    for (const [brand, pattern] of BRAND_PATTERNS) if (pattern.test(text)) return brand;
  }
  return null;
}

